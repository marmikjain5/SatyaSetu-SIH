function createMockDeclarations(
  data: Partial<Record<DeclarationFieldKey, { value: string; confidence: number; isPresent: boolean }>>
): Record<DeclarationFieldKey, DeclarationField> {
  const keys: DeclarationFieldKey[] = [
    'productName',
    'mrp',
    'unitSalePrice',
    'netQuantity',
    'manufacturer',
    'address',
    'importer',
    'countryOfOrigin',
    'packingDate',
    'manufacturingDate',
    'expiryDate',
    'batchNumber',
    'customerCare',
    'fssaiLicense',
    'barcode',
  ];

  const result = {} as Record<DeclarationFieldKey, DeclarationField>;

  for (const key of keys) {
    const item = data[key];
    result[key] = {
      key,
      label: key,
      value: item?.value || '',
      rawValue: item?.value || '',
      confidence: item?.confidence || (item?.isPresent ? 96 : 0),
      sourceText: item?.value || '',
      sourcePass: 'adaptive_threshold',
      boundingBox: {
        x0: 50,
        y0: 50,
        x1: 400,
        y1: 90,
        normalized: { x: 5, y: 5, width: 35, height: 4 },
      },
      validationStatus: item?.isPresent ? 'compliant' : 'missing',
      validationMessage: item?.isPresent ? 'Field declared and verified' : 'Field not declared',
      ruleCode: 'PCR-2011',
      ruleDescription: 'Mandatory statutory declaration under Legal Metrology',
      isMandatory: true,
      category: FIELD_CATEGORIES[key],
    };
  }

  return result;
}

